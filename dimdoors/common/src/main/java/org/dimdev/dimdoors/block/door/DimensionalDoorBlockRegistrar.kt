    private fun checkMutable(message: String) {
        check(!initialized) { "$message must be registered before dimensional door block registration is initialized." }
    }

    fun isMapped(location: ResourceLocation): Boolean = mappedDoorBlocks.containsKey(location)

    val gennedIds: MutableSet<ResourceLocation?>
        get() = mappedDoorBlocks.keys

    val generatedBlockMappings: MutableMap<ResourceLocation, ResourceLocation>
        get() = mappedDoorBlocks


    abstract class AutoGenDimensionalDoorBlock<T : EntranceRiftBlockEntity<*>>(
        settings: Properties,
        originalBlock: DoorSoundProvider
    ) : DimensionalDoorBlock<T>(
        settings, originalBlock.setType, !(originalBlock as Block).defaultBlockState().hasProperty(WATERLOGGED)
    ) {
        val originalBlock: Block = originalBlock as Block

        init {

            val builder = StateDefinition.Builder<Block, BlockState>(this)
            this.createBlockStateDefinition(builder)
            this.stateDefinition = builder.create(
                { obj: Block -> obj.defaultBlockState() },
                ::BlockState
            )

            registerDefaultState(stateDefinition.any())
            registerDefaultState(
                withPropertiesOf(this.originalBlock.defaultBlockState()).setValue(
                    TrapDoorBlock.WATERLOGGED,
                    false
                )
            )
        }

        override fun createBlockStateDefinition(builder: StateDefinition.Builder<Block, BlockState>) {
            super.createBlockStateDefinition(builder)
            (originalBlock as Block?)?.defaultBlockState()?.properties?.filterNot(EXISTING_DOOR_PROPERTIES::contains)
                ?.forEach(builder::add)
        }

        override fun getVisualBlockState(state: BlockState): BlockState {
            return this.originalBlock.withPropertiesOf(state)
        }

        companion object {
            val EXISTING_DOOR_PROPERTIES = listOf<Property<*>>(WATERLOGGED, HALF, OPEN, FACING, HINGE, POWERED)
        }
    }

    class DefaultAutoGenDoorBlock(settings: Properties, originalBlock: DoorSoundProvider) :
        AutoGenDimensionalDoorBlock<EntranceRiftBlockEntity.Impl>(settings, originalBlock) {
        override val riftBlockEnityType: BlockEntityType<EntranceRiftBlockEntity.Impl> get() = ModBlockEntityTypes.ENTRANCE_RIFT

        override fun useWithoutItem(
            state: BlockState,
            world: Level,
            pos: BlockPos,
            player: Player,
            hitResult: BlockHitResult
        ) = super.useWithoutItem(state, world, pos, player, hitResult)
    }

    abstract class AutoGenDimensionalTrapdoorBlock<T : EntranceRiftBlockEntity<T>>(
        settings: Properties,
        originalBlock: DoorSoundProvider
    ) : DimensionalTrapDoorBlock<T>(settings, originalBlock.setType), AutoGenTraversalRiftBlock<T> {
        override val originalBlock = originalBlock.cast<Block>()

        init {

            val builder = StateDefinition.Builder<Block, BlockState>(this)
            this.createBlockStateDefinition(builder)
            this.stateDefinition = builder.create(
                Block::defaultBlockState,
                ::BlockState
            )

            registerDefaultState(stateDefinition.any())
            registerDefaultState(withPropertiesOf(this.originalBlock.defaultBlockState()).setValue(WATERLOGGED, false))
        }

        override fun createBlockStateDefinition(builder: StateDefinition.Builder<Block, BlockState>) {
            super.createBlockStateDefinition(builder)
            (originalBlock as Block?)?.defaultBlockState()?.properties?.filterNot(EXISTING_TRAPDOOR_PROPERTIES::contains)
                ?.forEach(builder::add)
        }


        override fun getVisualBlockState(state: BlockState): BlockState = originalBlock.withPropertiesOf(state)

        companion object {
            val EXISTING_TRAPDOOR_PROPERTIES = listOf<Property<*>>(WATERLOGGED, HALF, OPEN, FACING, POWERED)
        }
    }

    class DefaultAutoGenTrapDoorBlock(settings: Properties, originalBlock: DoorSoundProvider) :
        AutoGenDimensionalTrapdoorBlock<EntranceRiftBlockEntity.Impl>(settings, originalBlock) {
        override val riftBlockEnityType: BlockEntityType<EntranceRiftBlockEntity.Impl>
            get() = ModBlockEntityTypes.ENTRANCE_RIFT
    }


    const val PREFIX: String = "block_ag_dim_"

    private val DEFAULT_PRODUCTION: DoorProduction = object : DoorProduction {
        override fun createDoor(context: GeneratedDoorContext, originalBlock: DoorBlock): Block {
            return DefaultAutoGenDoorBlock(context.properties, originalBlock)
        }

        override fun createTrapdoor(context: GeneratedDoorContext, originalBlock: TrapDoorBlock): Block {
            return DefaultAutoGenTrapDoorBlock(context.properties, originalBlock)
        }

        override fun onBlockRegistered(context: GeneratedDoorContext, generatedBlock: Block) {
            ModBlockEntityTypes.ENTRANCE_RIFT.addBlock(generatedBlock)
        }
    }

    private fun generatedId(location: ResourceLocation): ResourceLocation {
        return DimensionalDoors.id("$PREFIX${location.namespace}_${location.path}")
    }

    private fun createProperties(original: Block) = BlockBehaviour.Properties.ofFullCopy(original)
        .mapColor(original.defaultMapColor())
        .lightLevel { state -> original.withValuesOf(state).lightEmission }
        .isValidSpawn { state, level, pos, type -> original.withPropertiesOf(state).isValidSpawn(level, pos, type) }
        .isRedstoneConductor { state, level, pos -> original.withPropertiesOf(state).isRedstoneConductor(level, pos) }
        .isSuffocating { state, level, pos -> original.withPropertiesOf(state).isSuffocating(level, pos) }
        .isViewBlocking { state, level, pos -> original.withPropertiesOf(state).isViewBlocking(level, pos) }
        .hasPostProcess { state, level, pos -> original.withPropertiesOf(state).hasPostProcess(level, pos) }
        .emissiveRendering { state, level, pos -> original.withPropertiesOf(state).emissiveRendering(level, pos) }
        .requiresCorrectToolForDrops()

    private fun Block.withValuesOf(state: BlockState): BlockState = state.values.entries.fold(defaultBlockState()) { result, (property, value) ->
        if (result.hasProperty(property)) result.setValue(property as Property<Comparable<Any>>, value as Comparable<Any>) else result
    }

}
