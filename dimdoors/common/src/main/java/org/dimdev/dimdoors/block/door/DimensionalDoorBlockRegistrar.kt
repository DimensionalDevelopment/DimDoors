typealias TagMap<T> = MutableMap<TagKey<T>, MutableList<Holder<T>>>

typealias BlockTagMap = TagMap<Block>
typealias ItemTagMap = TagMap<Item>

object DimensionalDoorBlockRegistrar {
    private val mappedDoorBlocks = HashBiMap.create<ResourceLocation, ResourceLocation>()

    private val customDoorProductions = mutableMapOf<ResourceLocation, DoorProduction>()
    private val customDoorProductionRules = mutableListOf<DoorProductionRule>()
    private var initialized = false

    fun <T> populateTags(
        registry: Registry<T>,
        map: TagMap<T>,
        doorTag: TagKey<T>,
        predicate: TagKey<T>.() -> Boolean
    ): TagMap<T> {
        val key = registry.key()

        val autoGenerated = mappedDoorBlocks
            .mapNotNull { (dimdoor, base) ->
                registry.getHolder(dimdoor)
                    .getOrNull()?.let { ResourceKey.create(key, base) to it }
            }.toMap()

        val result: TagMap<T> = map.mapValuesTo(mutableMapOf()) { (tag, holders) ->
            if (tag.let(predicate)) holders.toMutableList()
            else (holders + holders.mapNotNull { it.unwrapKey().getOrNull()?.let(autoGenerated::get) }).toMutableList()
        }
        result[doorTag] = autoGenerated.values.toMutableList<Holder<T>>()
        return result
    }

    fun populateBlockTags(map: BlockTagMap): BlockTagMap =
        populateTags(BuiltInRegistries.BLOCK, map, ModBlockTags.DIMENSIONAL_DOORS) { false }

    fun populateItemTags(map: ItemTagMap): ItemTagMap =
        populateTags(BuiltInRegistries.ITEM, map, ModItemTags.DIMENSIONAL_DOORS) { false }

    fun getDimensionalVariant(block: Block): Block? {
        var id = block.builtInRegistryHolder().key().location()
        id = mappedDoorBlocks.inverse()[id] ?: return null

        return BuiltInRegistries.BLOCK.get(id)
    }

    interface DoorProduction {
        fun createDoor(context: GeneratedDoorContext, originalBlock: DoorBlock): Block?

        fun createTrapdoor(context: GeneratedDoorContext, originalBlock: TrapDoorBlock): Block?

        fun onBlockRegistered(context: GeneratedDoorContext, generatedBlock: Block) {
        }
    }

    fun interface DoorProductionSelector {
        fun test(id: ResourceLocation?, block: Block?): Boolean
    }

    private data class DoorProductionRule(val selector: DoorProductionSelector, val production: DoorProduction)

    @JvmRecord
    data class GeneratedDoorContext(
        val originalId: ResourceLocation,
        val generatedId: ResourceLocation,
        val properties: BlockBehaviour.Properties
    )

    fun handleEntry(location: ResourceLocation, original: Block) {
        if (!initialized) {
            RegisterDimensionalDoorProductionsCallback.EVENT.invoker().register(this)
            initialized = true
        }

        if (config.doorsConfig.isAllowed(location)) {
            val production = getProduction(location, original)
            if (original !is DimensionalDoorBlock<*> && original is DoorBlock) {
                registerDoor(location, original, production)
            } else if (original !is DimensionalTrapDoorBlock<*> && original is TrapDoorBlock) {
                registerTrapdoor(location, original, production)
            }
        }
    }

    private fun getProduction(location: ResourceLocation, original: Block): DoorProduction {
        val production = customDoorProductions.get(location)
        if (production != null) {
            return production
        }

        for (rule in customDoorProductionRules) {
            if (rule.selector.test(location, original)) {
                return rule.production
            }
        }

        return DEFAULT_PRODUCTION
    }

    private fun registerDoor(location: ResourceLocation, original: DoorBlock, production: DoorProduction) {
        val gennedId: ResourceLocation = generatedId(location)
        val context = GeneratedDoorContext(location, gennedId, createProperties(original))

        val result = production.createDoor(context, original)

        if (result != null) register(context, original, result, production)
    }

    private fun registerTrapdoor(location: ResourceLocation, original: TrapDoorBlock, production: DoorProduction) {
        val gennedId: ResourceLocation = generatedId(location)
        val context = GeneratedDoorContext(location, gennedId, createProperties(original))

        val result = production.createTrapdoor(context, original)

        if (result != null) register(context, original, result, production)
    }

    private fun register(context: GeneratedDoorContext, original: Block, dimBlock: Block, production: DoorProduction) {
        var dimBlock = dimBlock
        if (mappedDoorBlocks.containsKey(context.generatedId)) return

        dimBlock = Registry.register(BuiltInRegistries.BLOCK, context.generatedId, dimBlock)
        mappedDoorBlocks[context.generatedId] = context.originalId
        DimensionalDoorItemRegistrar.notifyBlockMapped(original, dimBlock)

        production.onBlockRegistered(context, dimBlock)
    }

    operator fun get(location: ResourceLocation?): ResourceLocation? {
        return mappedDoorBlocks[location]
    }

    fun registerCustomDoorProduction(id: ResourceLocation, production: DoorProduction) {
        checkMutable("Custom dimensional door production for $id")
        val previous = customDoorProductions.putIfAbsent(id, production)
        require(!(previous != null && previous !== production)) { "Custom dimensional door production is already registered for $id." }
    }

    fun registerCustomDoorProduction(ids: MutableCollection<ResourceLocation>, production: DoorProduction) {
        for (id in ids) {
            registerCustomDoorProduction(id, production)
        }
    }

    fun registerCustomDoorProduction(selector: DoorProductionSelector, production: DoorProduction) {
        checkMutable("Custom dimensional door production rule")
        customDoorProductionRules.add(DoorProductionRule(selector, production))
    }

